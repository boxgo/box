package kafka

import (
	"testing"

	"github.com/xdg/scram"
)

// testSCRAMExchange drives a full SCRAM conversation between the client
// implementation and a xdg/scram server conversation, then asserts both
// sides complete and the server authenticates the user.
func testSCRAMExchange(t *testing.T, mechanism SASLMechanism, hashFcn scram.HashGeneratorFcn) {
	t.Helper()

	const (
		username = "admin"
		password = "admin-secret"
		salt     = "salty-salt"
		iters    = 4096
	)

	// Server side: look up stored credentials derived from the same secret.
	credClient, credErr := hashFcn.NewClient(username, password, "")
	if credErr != nil {
		t.Fatal(credErr)
	}

	server, err := hashFcn.NewServer(func(user string) (scram.StoredCredentials, error) {
		if user != username {
			t.Fatalf("unexpected username: %s", user)
		}

		return credClient.GetStoredCredentials(scram.KeyFactors{Salt: salt, Iters: iters}), nil
	})
	if err != nil {
		t.Fatal(err)
	}

	serverConvo := server.NewConversation()

	// Client side: generated by the config default generator.
	client := SASLConfig{Mechanism: mechanism}.defaultSCRAMClientGenerator()

	if err = client.Begin(username, password, ""); err != nil {
		t.Fatal(err)
	}

	clientFirst, err := client.Step("")
	if err != nil {
		t.Fatal(err)
	}

	serverFirst, err := serverConvo.Step(clientFirst)
	if err != nil {
		t.Fatal(err)
	}

	clientFinal, err := client.Step(serverFirst)
	if err != nil {
		t.Fatal(err)
	}

	serverFinal, err := serverConvo.Step(clientFinal)
	if err != nil {
		t.Fatal(err)
	}

	if _, err := client.Step(serverFinal); err != nil {
		t.Fatal(err)
	}

	if !client.Done() {
		t.Fatalf("[%s] client conversation not done", mechanism)
	}
	if !serverConvo.Done() || !serverConvo.Valid() {
		t.Fatalf("[%s] server did not authenticate client", mechanism)
	}
}

func TestXDGSCRAMClient_SCRAMSHA256Exchange(t *testing.T) {
	testSCRAMExchange(t, SASLTypeSCRAMSHA256, scram.SHA256)
}

func TestXDGSCRAMClient_SCRAMSHA512Exchange(t *testing.T) {
	testSCRAMExchange(t, SASLTypeSCRAMSHA512, sha512Fcn)
}
